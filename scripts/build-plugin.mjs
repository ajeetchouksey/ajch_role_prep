#!/usr/bin/env node
/**
 * build-plugin.mjs — package the .claude/ kit as an installable Claude Code plugin.
 *
 * .claude/ stays the single source; plugin/ is generated, never edited by hand.
 * Output:
 *   plugin/.claude-plugin/plugin.json
 *   plugin/agents/  plugin/skills/  plugin/commands/
 *   plugin/hooks/hooks.json + hook scripts   (use ${CLAUDE_PLUGIN_ROOT})
 *   plugin/scripts/                           (validators the hooks run)
 * Install elsewhere with:
 *   /plugin marketplace add ajeetchouksey/ajch_role_prep
 *   /plugin install roleprep-kit@aaryaai-roleprep
 */
import { cpSync, rmSync, mkdirSync, writeFileSync, readFileSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'plugin');
const pkg = JSON.parse(readFileSync(join(ROOT, 'package.json'), 'utf-8'));

rmSync(OUT, { recursive: true, force: true });
mkdirSync(join(OUT, '.claude-plugin'), { recursive: true });
for (const dir of ['agents', 'skills', 'commands']) cpSync(join(ROOT, '.claude', dir), join(OUT, dir), { recursive: true });
cpSync(join(ROOT, '.claude', 'hooks'), join(OUT, 'hooks'), { recursive: true });
mkdirSync(join(OUT, 'scripts'), { recursive: true });
for (const f of ['validate-content.mjs', 'check-options.mjs', 'check-docs.mjs', 'build-catalog.mjs']) cpSync(join(ROOT, 'scripts', f), join(OUT, 'scripts', f));

writeFileSync(join(OUT, '.claude-plugin', 'plugin.json'), JSON.stringify({
  name: 'roleprep-kit',
  version: pkg.version,
  description: 'Agents, skills, commands and hooks for authoring, building and testing Role Prep: AI-role interview practice with Tech, Tech Lead and Leadership bars.',
  author: { name: 'AaryaAI' },
  homepage: 'https://aaryaai.dev/roleprep',
  repository: 'https://github.com/ajeetchouksey/ajch_role_prep',
}, null, 2) + '\n');

const hook = (file) => ({ type: 'command', command: `node "\${CLAUDE_PLUGIN_ROOT}/hooks/${file}"` });
writeFileSync(join(OUT, 'hooks', 'hooks.json'), JSON.stringify({
  hooks: {
    PreToolUse: [{ matcher: 'Write|Edit|MultiEdit', hooks: [hook('guard-protected.mjs')] }],
    PostToolUse: [{ matcher: 'Write|Edit|MultiEdit', hooks: [hook('validate-on-write.mjs')] }],
  },
}, null, 2) + '\n');

writeFileSync(join(OUT, 'README.md'), '# roleprep-kit\n\nGenerated by `scripts/build-plugin.mjs` from `.claude/`. Do not edit here; edit `.claude/` and rebuild.\n');
console.log(`plugin/ built: roleprep-kit ${pkg.version}`);
